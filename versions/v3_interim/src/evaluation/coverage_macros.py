"""
LaTeX macros describing how far each O1 trajectory ran (for the report).

Usage:
  python src/evaluation/coverage_macros.py --results_dir results/o1_paired_v3 --tag Main --out generated/coverage_Main.tex
"""

import argparse
import glob
import json
import os

import pandas as pd

TRACK_KEYS = {"positive": "Pos", "negative": "Neg", "control": "Ctl"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results_dir", required=True)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    assert args.tag.isalpha()

    rows = []
    for path in glob.glob(os.path.join(args.results_dir, "**", "claims_drift_results.jsonl"), recursive=True):
        with open(path, encoding="utf-8") as f:
            rows += [json.loads(line) for line in f if line.strip()]
    df = pd.DataFrame(rows).drop_duplicates(subset=["claim_id", "track", "turn"], keep="last")

    last = df.groupby(["claim_id", "track"])["turn"].max()
    horizon = int(df["turn"].max())
    min_reached = int(last.min())
    turn0 = df[(df["turn"] == 0)].drop_duplicates("claim_id")
    parsed0 = turn0[turn0["verdict"].notna()]

    macros = {
        "Trajectories": str(len(last)),
        "Items": str(df["claim_id"].nunique()),
        "TurnBudget": str(horizon),
        "AllReachTurn": str(min_reached),
        "CompleteTrajectories": str(int((last == horizon).sum())),
        "AccStartOverall": f"{100 * (parsed0['verdict'] == parsed0['ground_truth_verdict']).mean():.1f}",
        "ParseFailPct": f"{100 * df['verdict'].isna().mean():.1f}",
    }
    # Agreement of each probe with the parsed verdict (probe > 50% iff "Valid"), over turns 0..min_reached
    early = df[(df["turn"] <= min_reached) & df["verdict"].notna()]
    is_valid = early["verdict"] == "Valid"
    macros["ProbeAgree"] = f"{100 * ((early['target_token_confidence'] > 50) == is_valid).mean():.1f}"
    if "verifier_prob_valid" in early:
        macros["SelfCheckAgree"] = f"{100 * ((early['verifier_prob_valid'] > 50) == is_valid).mean():.1f}"
    for track, key in TRACK_KEYS.items():
        t = last.xs(track, level="track") if track in last.index.get_level_values("track") else None
        if t is not None:
            macros[f"Complete{key}"] = str(int((t == horizon).sum()))

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("% Generated by coverage_macros.py; do not edit by hand.\n")
        for k, v in macros.items():
            f.write(f"\\newcommand{{\\{args.tag}{k}}}{{{v}}}\n")
    print(open(args.out).read())


if __name__ == "__main__":
    main()
